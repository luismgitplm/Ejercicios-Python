"""4. Escribe un programa que recoja tres números y calcule su media aritmética."""
num1 = int(input("Indique un número: "))
num2 = int(input("Indique un segundo número: "))
num3 = int(input("Indique un tercer número: "))

media = (num1 + num2 + num3) / 3
print ("La media de los tres números indicados es: ",media)